-- ----------------------------------------------------------------------------
-- BUSINESS_CATEGORIES  (industries — Nurseries, Retail, Hospitals, ...)
-- ----------------------------------------------------------------------------
CREATE TABLE BUSINESS_CATEGORIES (
    ID              NUMBER          GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    SLUG            VARCHAR2(120)   NOT NULL,
    NAME            VARCHAR2(160)   NOT NULL,
    DESCRIPTION     CLOB,
    IS_ACTIVE       NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_BUSINESS_CATEGORIES PRIMARY KEY (ID)
);

COMMENT ON TABLE BUSINESS_CATEGORIES IS 'Industry categories shown on the Industries pages (retail, hospitals, pharmacies, ...).';

-- ----------------------------------------------------------------------------
-- SERVICES  (solutions — Billing Software, GST Billing, ...)
-- ----------------------------------------------------------------------------
CREATE TABLE SERVICES (
    ID              NUMBER          GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    CATEGORY_ID     NUMBER,
    SLUG            VARCHAR2(120)   NOT NULL,
    NAME            VARCHAR2(160)   NOT NULL,
    DESCRIPTION     CLOB,
    IS_ACTIVE       NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SERVICES PRIMARY KEY (ID)
);

COMMENT ON TABLE SERVICES IS 'Solution offerings shown on the Solutions pages (billing, inventory, GST, ...).';

-- ----------------------------------------------------------------------------
-- SOFTWARE_FEATURES  (feature line items, optionally attached to a service)
