    NOTE                    CLOB            NOT NULL,
    FOLLOW_UP_DATE          DATE            NOT NULL,
    STATUS                  VARCHAR2(20)    DEFAULT 'pending' NOT NULL,
    CREATED_BY_ADMIN_ID     NUMBER,
    CREATED_AT              TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT              TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LEAD_FOLLOWUPS PRIMARY KEY (ID)
);

-- ----------------------------------------------------------------------------
-- WHATSAPP_MESSAGES  (stored WhatsApp communication history per lead)
-- ----------------------------------------------------------------------------
CREATE TABLE WHATSAPP_MESSAGES (
    ID              NUMBER          GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    LEAD_ID         NUMBER          NOT NULL,
    DIRECTION       VARCHAR2(10)    NOT NULL,
    MESSAGE_TEXT    CLOB            NOT NULL,
    -- Language the stored message was sent/received in ('en' | 'ta').
    LANGUAGE_CODE   VARCHAR2(5)     DEFAULT 'en' NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_WHATSAPP_MESSAGES PRIMARY KEY (ID)
);

-- ----------------------------------------------------------------------------
-- ADMIN_USERS  (Oracle APEX admin portal + JWT API authentication)
-- ----------------------------------------------------------------------------
CREATE TABLE ADMIN_USERS (
    ID                  NUMBER          GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    FULL_NAME           VARCHAR2(160)   NOT NULL,
    EMAIL               VARCHAR2(255)   NOT NULL,
    HASHED_PASSWORD     VARCHAR2(255)   NOT NULL,
    ROLE                VARCHAR2(20)    DEFAULT 'support_agent' NOT NULL,
    IS_ACTIVE           NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ADMIN_USERS PRIMARY KEY (ID)
);

-- ----------------------------------------------------------------------------
-- ADMIN_REFRESH_TOKENS  (server-side revocable JWT refresh tokens)
-- ----------------------------------------------------------------------------
CREATE TABLE ADMIN_REFRESH_TOKENS (
    ID              NUMBER          GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ADMIN_ID        NUMBER          NOT NULL,
    TOKEN_HASH      VARCHAR2(64)    NOT NULL,
    EXPIRES_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    REVOKED_AT      TIMESTAMP WITH TIME ZONE,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ADMIN_REFRESH_TOKENS PRIMARY KEY (ID)
);
