CREATE TABLE SOFTWARE_FEATURES (
    ID              NUMBER          GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    SERVICE_ID      NUMBER,
    NAME            VARCHAR2(160)   NOT NULL,
    DESCRIPTION     CLOB,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SOFTWARE_FEATURES PRIMARY KEY (ID)
);

-- ----------------------------------------------------------------------------
-- CUSTOMER_LEADS  (parent record for every enquiry)
-- ----------------------------------------------------------------------------
CREATE TABLE CUSTOMER_LEADS (
    ID              NUMBER          GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    LEAD_ID         VARCHAR2(32)    NOT NULL,
    FULL_NAME       VARCHAR2(160)   NOT NULL,
    EMAIL           VARCHAR2(255)   NOT NULL,
    PHONE           VARCHAR2(20)    NOT NULL,
    MESSAGE         CLOB,
    SOURCE          VARCHAR2(32)    NOT NULL,
    STATUS          VARCHAR2(32)    DEFAULT 'new' NOT NULL,
    -- Preferred language the customer submitted in ('en' | 'ta') so admin
    -- staff and any future automated WhatsApp/email follow-up reply in
    -- the language the customer actually used.
    PREFERRED_LANGUAGE VARCHAR2(5)  DEFAULT 'en' NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CUSTOMER_LEADS PRIMARY KEY (ID)
);

COMMENT ON TABLE CUSTOMER_LEADS IS 'Parent enquiry record — every contact-form submission and demo request creates one row here.';

-- ----------------------------------------------------------------------------
-- DEMO_REQUESTS  (one-to-one extension of CUSTOMER_LEADS)
-- ----------------------------------------------------------------------------
CREATE TABLE DEMO_REQUESTS (
    ID                      NUMBER          GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    LEAD_ID                 NUMBER          NOT NULL,
    COMPANY_NAME            VARCHAR2(200)   NOT NULL,
    BUSINESS_TYPE           VARCHAR2(60)    NOT NULL,
    INDUSTRY                VARCHAR2(80)    NOT NULL,
    CITY                    VARCHAR2(100)   NOT NULL,
    STATE                   VARCHAR2(100)   NOT NULL,
    BUSINESS_REQUIREMENT    CLOB            NOT NULL,
    PREFERRED_DEMO_DATE     DATE            NOT NULL,
    PREFERRED_DEMO_TIME     VARCHAR2(10)    NOT NULL,
    DEMO_MODE               VARCHAR2(20)    NOT NULL,
    CREATED_AT              TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT              TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_DEMO_REQUESTS PRIMARY KEY (ID)
);

-- ----------------------------------------------------------------------------
-- LEAD_FOLLOWUPS  (follow-up tasks/notes managed from the APEX admin portal)
